#!/usr/bin/env python3
"""把仪表原厂底图压成色值表，生成 instrument/bgmap_data.go。

来源：仪表 /app/hmi/bin/main.kzb 内 Resource Files/Images/bg_cluster_{1,2}_{day,night}.png
（1920×720）。KZBF 条目内部是 20 字节头 + 完整 PNG，按 PNG magic/IEND 截取即可。

用法：
  python3 gen_bgmap.py <含四张 png 的目录> [输出 .go 路径]
"""
import base64
import pathlib
import sys

from PIL import Image

GW, GH = 96, 36
ORDER = [
    (0, 0, "bg_cluster_1_day.png"),
    (0, 1, "bg_cluster_1_night.png"),
    (1, 0, "bg_cluster_2_day.png"),
    (1, 1, "bg_cluster_2_night.png"),
]


def main():
    src = pathlib.Path(sys.argv[1])
    out = pathlib.Path(sys.argv[2]) if len(sys.argv) > 2 else pathlib.Path("bgmap_data.go")
    tables = {}
    for variant, night, name in ORDER:
        im = Image.open(src / name).convert("RGB")
        if im.size != (1920, 720):
            raise SystemExit("%s 尺寸异常 %s" % (name, im.size))
        small = im.resize((GW, GH), Image.BOX)
        tables[(variant, night)] = small.tobytes()
        # 重建误差自检
        sp = small.load()
        p = im.load()
        mx = 0
        for y in range(0, 720, 5):
            fy = (y + 0.5) * GH / 720 - 0.5
            y0 = max(0, int(fy)); y1 = min(GH - 1, y0 + 1); ty = fy - y0
            for x in range(0, 1920, 5):
                fx = (x + 0.5) * GW / 1920 - 0.5
                x0 = max(0, int(fx)); x1 = min(GW - 1, x0 + 1); tx = fx - x0
                for c in range(3):
                    a = sp[x0, y0][c] * (1 - tx) + sp[x1, y0][c] * tx
                    b = sp[x0, y1][c] * (1 - tx) + sp[x1, y1][c] * tx
                    mx = max(mx, abs((a * (1 - ty) + b * ty) - p[x, y][c]))
        print("%-24s 网格重建最大误差 %.1f 级" % (name, mx))

    lines = []
    lines.append("// Code generated by tools/gen_bgmap.py; DO NOT EDIT.")
    lines.append("")
    lines.append("package main")
    # 注意：数据文件只放字符串常量，base64 解码在 bgmap.go 里做，
    # 这里不能生成 import，否则会多一个"未使用 import"编译不过
    lines.append("")
    lines.append("// 底图色值表：仪表原厂 main.kzb 内 bg_cluster_{1,2}_{day,night}.png 的")
    lines.append("// %d×%d 降采样（每格 20×20 px），base64 存 RGB 三字节/格。" % (GW, GH))
    lines.append("// 重建误差：cluster_2 ≤1.3 级；cluster_1 整体 ≤8.5 级（中上部有一处硬边），")
    lines.append("// 但两套在歌词卡片所在的右半屏都 ≤1.0 级。只存色值，不存原图。")
    lines.append("// 索引：[套系][0=白天 1=夜间]，套系 0=bg_cluster_1、1=bg_cluster_2。")
    lines.append("var bgGridData = [2][2]string{")
    for variant in (0, 1):
        lines.append("\t{")
        for night in (0, 1):
            b64 = base64.b64encode(tables[(variant, night)]).decode()
            lines.append("\t\t\"%s\"," % b64)
        lines.append("\t},")
    lines.append("}")
    lines.append("")
    lines.append("const (")
    lines.append("\tbgGridW = %d" % GW)
    lines.append("\tbgGridH = %d" % GH)
    lines.append(")")
    lines.append("")
    out.write_text("\n".join(lines), encoding="utf-8")
    print("写入 %s (%d 字节)" % (out, out.stat().st_size))


if __name__ == "__main__":
    main()
